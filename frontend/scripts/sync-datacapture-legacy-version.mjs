import crypto from "crypto";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "../..");
const legacyPath = path.join(root, "js/datacapture.js");
const outPath = path.join(
  root,
  "frontend/src/pages/datacapture/dataCaptureLegacyScriptUrl.js",
);

if (!fs.existsSync(legacyPath)) {
  console.warn("[sync-datacapture-legacy-version] js/datacapture.js not found, skipping");
  process.exit(0);
}

const content = fs.readFileSync(legacyPath);
const version = crypto.createHash("sha256").update(content).digest("hex").slice(0, 12);
const mtime = fs.statSync(legacyPath).mtime.toISOString();

const module = `/** Auto-generated by scripts/sync-datacapture-legacy-version.mjs — do not edit. */
/** Content hash of js/datacapture.js (updates when you run npm run build / dev). */
export const DATA_CAPTURE_LEGACY_ASSET_VERSION = ${JSON.stringify(version)};
export const DATA_CAPTURE_LEGACY_SCRIPT_PATH = ${JSON.stringify(`js/datacapture.js?v=${version}`)};
export const DATA_CAPTURE_LEGACY_ASSET_MTIME = ${JSON.stringify(mtime)};
`;

fs.writeFileSync(outPath, module);
console.log(`[sync-datacapture-legacy-version] js/datacapture.js → v=${version}`);
